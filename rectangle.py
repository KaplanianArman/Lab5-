def _check(*values):
    '''
    Проверяет, что все значения являются неотрицательными числами

        Параметры:
            values : проверяемые значения

        Исключения:
            TypeError : если значение не является числом (int или float)
            ValueError : если значение отрицательное
    '''
    for value in values:
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise TypeError(f"Ожидалось число, получено {type(value).__name__}")
        if value < 0:
            raise ValueError("Значение не может быть отрицательным")


def area(a, b):
    '''
    Возвращает площадь прямоугольника

        Параметры:
            a (int) : целое положительное число (ширина прямоугольника)
            b (int) : целое положительное число (длина прямоугольника)
        
        Возвращаемое значение:
            area (int) : целое положительное число (площадь прямоугольника)
    '''
    _check(a, b)
    return a * b


def perimeter(a, b):
    '''
    Возвращает периметр прямоугольника

        Параметры:
            a (int) : целое положительное число (ширина прямоугольника)
            b (int) : целое положительное число (длина прямоугольника)
        
        Возвращаемое значение:
            perimeter (int) : целое положительное число (периметр прямоугольника)
    '''
    _check(a, b)
    return (a + b) * 2
